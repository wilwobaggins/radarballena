-- =========================
-- HELPERS
-- =========================

create or replace function public.set_updated_at()
returns trigger as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$ language plpgsql;


-- =========================
-- AUTH / USERS
-- =========================

create table if not exists public.users (
  id text primary key,
  email text not null unique,
  "passwordHash" text not null,
  role text not null default 'user',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();


create table if not exists public.user_sessions (
  id text primary key,
  "userId" text not null,
  "tokenHash" text not null unique,
  "expiresAt" timestamptz not null,
  "createdAt" timestamptz not null default now(),

  constraint user_sessions_userId_fkey
    foreign key ("userId") references public.users(id)
    on delete cascade
);

create index if not exists user_sessions_userId_idx on public.user_sessions ("userId");
create index if not exists user_sessions_expiresAt_idx on public.user_sessions ("expiresAt");


