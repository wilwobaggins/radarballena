-- =========================
-- DEEPSIGNAL / MARKETS
-- =========================
-- Nota: esta tabla representa el mercado analizado.
-- No reemplaza alerts. Alerts sigue siendo "alerta de whale".

create table if not exists public.markets (
  id uuid primary key default gen_random_uuid(),

  "externalMarketId" text not null,
  platform text not null default 'polymarket',

  title text not null,
  description text,
  category text,
  url text,

  "closeDate" timestamptz,
  "currentProbability" double precision,
  "previousProbability24h" double precision,
  "probabilityChange24h" double precision,
  volume double precision,
  liquidity double precision,
  outcomes jsonb,

  "lastUpdated" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),

  constraint markets_platform_external_unique unique (platform, "externalMarketId")
);

create index if not exists markets_platform_idx on public.markets (platform);
create index if not exists markets_category_idx on public.markets (category);
create index if not exists markets_closeDate_idx on public.markets ("closeDate");
create index if not exists markets_currentProbability_idx on public.markets ("currentProbability");

drop trigger if exists markets_set_updated_at on public.markets;
create trigger markets_set_updated_at
before update on public.markets
for each row execute function public.set_updated_at();


create table if not exists public.alerts (
  id integer generated by default as identity primary key,

  "whaleId" text not null,
  "whaleName" text not null,
  action text not null,
  answer text not null,
  "marketTitle" text not null,

  "marketId" text,
  "deepMarketId" uuid,
  "polymarketUrl" text,
  "eventSlug" text,
  "telegramDate" timestamptz,

  resolved boolean not null default false,
  result text,
  "isWin" boolean,

  "sizeUsd" double precision not null,
  "priceCents" integer not null,
  shares integer not null,
  "rawText" text not null,
  hash text not null unique,
  "createdAt" timestamptz not null default now(),

  constraint alerts_whaleId_fkey
    foreign key ("whaleId") references public.whales(id)
    on update cascade
    on delete restrict,

  constraint alerts_deepMarketId_fkey
    foreign key ("deepMarketId") references public.markets(id)
    on update cascade
    on delete set null
);

create index if not exists alerts_whaleId_idx on public.alerts ("whaleId");
create index if not exists alerts_marketId_idx on public.alerts ("marketId");
create index if not exists alerts_deepMarketId_idx on public.alerts ("deepMarketId");
create index if not exists alerts_eventSlug_idx on public.alerts ("eventSlug");
create index if not exists alerts_createdAt_idx on public.alerts ("createdAt");


create table if not exists public.user_channels (
  id text primary key,
  "userId" text not null,
  "channelId" text not null,
  unlocked boolean not null default false,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),

  constraint user_channels_userId_fkey
    foreign key ("userId") references public.users(id)
    on delete cascade,

  constraint user_channels_channelId_fkey
    foreign key ("channelId") references public.channels(id)
    on delete cascade,

  constraint user_channels_user_channel_unique unique ("userId", "channelId")
);

create index if not exists user_channels_userId_idx on public.user_channels ("userId");
create index if not exists user_channels_channelId_idx on public.user_channels ("channelId");

drop trigger if exists user_channels_set_updated_at on public.user_channels;
create trigger user_channels_set_updated_at
before update on public.user_channels
for each row execute function public.set_updated_at();


